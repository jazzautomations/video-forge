#!/usr/bin/env python3
"""Compile a small storyboard JSON to a runnable Remotion project without model-authored JSX."""
import argparse
import json
import shutil
from component_sources import resolve as resolve_component, copy_graph
from pathlib import Path
import sys

def _taste_lint(data):
    """Run the deterministic taste gate (scripts/lint_taste.py) as part of --check, so the
    golden path enforces it for free — a weak model can't ship leaked placeholder text or
    narration that overruns its beat just by skipping the lint step."""
    try:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import lint_taste
        return lint_taste.lint(data)
    except Exception as e:
        return {'ok': True, 'fails': [], 'warns': [f'taste lint unavailable: {e}'], 'checks': {}}

ROOT = Path(__file__).resolve().parents[1]
KINDS = {'title', 'character', 'screen', 'three', 'component'}

# Loads the theme's vendored .woff2 (public/fonts) via the FontFace API and holds the
# render with delayRender until each face is ready, so a frame never snapshots in a
# fallback font. Fully local, no web-font network request. %s is the face list (JSON).
FONT_LOADER = """// Auto-generated by build_project.py — do not edit. Vendored local fonts (SIL OFL 1.1).
import {staticFile, delayRender, continueRender} from 'remotion';
type Face = {family: string; weight: number; file: string};
const faces: Face[] = %s;
for (const {family, weight, file} of faces) {
  const handle = delayRender(`font:${file}`);
  const ff = new FontFace(family, `url(${staticFile('fonts/' + file)}) format('woff2')`, {weight: String(weight), style: 'normal', display: 'block'});
  ff.load().then((loaded) => {(document as any).fonts.add(loaded); continueRender(handle);}).catch(() => continueRender(handle));
}
"""

def validate(data):
    errors=[]
    if not isinstance(data,dict): return ['storyboard: expected an object']
    for key in ['width','height','fps']:
        v=data.get(key)
        if not isinstance(v,int) or isinstance(v,bool) or v<=0:
            errors.append(f'{key}: expected a positive integer')
    if not errors:
        if data['width']%2 or data['height']%2: errors.append('width/height: even dimensions required for H.264 delivery')
        if data['fps']>120: errors.append('fps: maximum 120 for this starter')
    scenes=data.get('scenes')
    if not isinstance(scenes,list) or not scenes:
        errors.append('scenes: expected a nonempty array')
        return errors
    if len(scenes)>100: errors.append('scenes: maximum 100 entries')
    for i,s in enumerate(scenes):
        at=f'scenes[{i}]'
        if not isinstance(s,dict):
            errors.append(f'{at}: expected an object');continue
        if s.get('kind') not in KINDS: errors.append(f'{at}.kind: choose {sorted(KINDS)}')
        if not isinstance(s.get('seconds'),(int,float)) or isinstance(s.get('seconds'),bool) or not 0<float(s.get('seconds',0))<=300: errors.append(f'{at}.seconds: expected a number in (0,300]')
        if s.get('kind')=='component':
            try:resolve_component(s.get('component'))
            except ValueError as error:errors.append(f'{at}: {error}')
        if 'narration' in s and not isinstance(s['narration'],str): errors.append(f'{at}.narration: expected script text')
        if s.get('kind')=='title' and not isinstance(s.get('title'),str): errors.append(f'{at}.title: expected a string')
        if s.get('kind')=='screen':
            for k in ['src','sourceWidth','sourceHeight','keys']:
                if k not in s: errors.append(f'{at}.{k}: required for screen scene')
            if not isinstance(s.get('keys'),list) or not s.get('keys'): errors.append(f'{at}.keys: expected camera key array')
            else:
                previous=-1
                for j,k in enumerate(s['keys']):
                    if not isinstance(k,dict) or any(not isinstance(k.get(f),(int,float)) for f in ['frame','cx','cy','zoom']): errors.append(f'{at}.keys[{j}]: needs numeric frame,cx,cy,zoom');continue
                    if k['frame']<0 or k['frame']<=previous or k['zoom']<=0: errors.append(f'{at}.keys[{j}]: increasing frames and positive zoom required')
                    previous=k['frame']
                    # The camera must stay inside the recording: a key that reveals the empty
                    # background reads as a letterbox mistake. Opt in with allowBackground.
                    sw,sh,z=s.get('sourceWidth'),s.get('sourceHeight'),k['zoom']
                    if isinstance(sw,int) and isinstance(sh,int) and sw>0 and sh>0 and not s.get('allowBackground'):
                        W,H=data['width'],data['height'];half_w,half_h=W/(2*z),H/(2*z)
                        if not (half_w<=k['cx']<=sw-half_w and half_h<=k['cy']<=sh-half_h):
                            errors.append(f'{at}.keys[{j}]: at zoom {z} the camera shows outside the recording; keep cx in [{half_w:.0f},{sw-half_w:.0f}] and cy in [{half_h:.0f},{sh-half_h:.0f}], raise zoom, or set allowBackground:true on purpose')
            for dim in ['sourceWidth','sourceHeight']:
                if not isinstance(s.get(dim),int) or s.get(dim,0)<=0:errors.append(f'{at}.{dim}: positive pixels required')
            if not isinstance(s.get('src'),str):errors.append(f'{at}.src: expected public-relative path')
    if not errors and 'durationSeconds' in data:
        total=sum(s['seconds'] for s in scenes)
        if not isinstance(data['durationSeconds'],(int,float)) or abs(total-data['durationSeconds'])>1/data['fps']:
            errors.append(f'durationSeconds: scene sum is {total}')
    return errors

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('storyboard',type=Path)
    ap.add_argument('--out',type=Path)
    ap.add_argument('--check',action='store_true')
    args=ap.parse_args()
    data=json.loads(args.storyboard.read_text())
    errors=validate(data)
    if errors:
        print(json.dumps({'ok':False,'errors':errors},indent=2));raise SystemExit(1)
    if args.check:
        taste=_taste_lint(data)
        ok=bool(taste.get('ok',True))
        print(json.dumps({'ok':ok,'scenes':len(data['scenes']),'taste':taste},indent=2,ensure_ascii=False))
        raise SystemExit(0 if ok else 1)
    if not args.out:ap.error('--out is required unless --check is used')
    if args.out.exists():ap.error('Output exists. To keep an edited project pass --resume to scripts/run.py; to regenerate from scratch choose a NEW --out directory.')
    out=args.out; (out/'src').mkdir(parents=True);(out/'public').mkdir();(out/'out').mkdir()
    shutil.copy2(args.storyboard,out/'storyboard.json')
    (out/'.video-forge-project').write_text('generated by video-forge\n')
    kinds={s['kind'] for s in data['scenes']}
    imports=["import React from 'react';", "import {AbsoluteFill,Composition,Sequence,registerRoot,staticFile,useCurrentFrame,interpolate,Easing,Audio} from 'remotion';", "import rawSpec from '../storyboard.json'; const spec: {width:number;height:number;fps:number;background?:string;textColor?:string;accent?:string;fontFamily?:string;displayFont?:string;textFont?:string;fonts?:{family:string;weight:number;file:string}[];titleAdvance?:number;transition?:string;scenes:any[];brand?:string}=rawSpec;"]
    for name in ['EditorialTitle','DirectedBeat','MotionCaptions']:
        shutil.copy2(ROOT/f'library/scenes/{name}.tsx',out/f'src/{name}.tsx')
        imports.append(f"import {{{name}}} from './{name}';")
    (out/'production.json').write_text(json.dumps({'narration':False,'music':False,'pages':[]})+'\n')
    imports.append("import production from '../production.json';")
    if 'character' in kinds:
        shutil.copy2(ROOT/'library/scenes/CharacterPresenter.tsx',out/'src/CharacterPresenter.tsx')
        imports.append("import {CharacterPresenter,defaultCharacterProps} from './CharacterPresenter';")
    for kind,name in [('screen','ScreenFocus'),('three','ProceduralObject3D')]:
        if kind in kinds:
            shutil.copy2(ROOT/f'library/scenes/{name}.tsx',out/f'src/{name}.tsx')
            imports.append(f"import {{{name}}} from './{name}';")
    # Vendored fonts: copy just the faces this theme needs into public/fonts, ship the
    # OFL license beside them, and emit a local FontFace loader the entry imports.
    fonts=data.get('fonts') or []
    if fonts:
        (out/'public/fonts').mkdir(parents=True,exist_ok=True)
        srcdir=ROOT/'assets/fonts';seen=set()
        for face in fonts:
            f=face['file']
            if f in seen:continue
            seen.add(f)
            src=srcdir/f
            if not src.exists():raise ValueError(f'theme references missing font file {f}; run scripts/vendor_fonts.py')
            shutil.copy2(src,out/'public/fonts'/f)
        if (srcdir/'OFL.txt').exists():shutil.copy2(srcdir/'OFL.txt',out/'public/fonts/OFL.txt')
        faces_json=json.dumps([{'family':x['family'],'weight':x['weight'],'file':x['file']} for x in fonts])
        (out/'src/fonts.ts').write_text(FONT_LOADER%faces_json)
        imports.insert(1,"import './fonts';")
    component_cases=[];component_deps=set()
    for i,scene in enumerate(data['scenes']):
        if scene['kind']!='component':continue
        base,source,name,defaults,is_schema=resolve_component(scene['component'])
        family=scene['component'].split('/')[0]
        component_deps.update(copy_graph(base,source,out/'src/vendor'/family))
        rel=(Path('vendor')/family/source.relative_to(base)).as_posix().removesuffix('.tsx')
        imports.append(f"import {{{name} as Piece{i},{defaults} as Defaults{i}}} from './{rel}';")
        props=f"Defaults{i}.parse({{placement:'center',fontFamily:spec.fontFamily??'Arial',color:spec.textColor,accentColor:spec.accent,...s.props}})" if is_schema else f"{{...Defaults{i},backgroundColor:spec.background,textColor:spec.textColor,accentColor:spec.accent,...s.props}}"
        # onda components read the theme from CSS custom properties (var(--onda-accent) etc.),
        # NOT only from props — set them on the wrapper so every onda scene adopts the palette
        # (otherwise e.g. a chapter number keeps onda's default rose in a green film).
        # onda vars need `as any` — Remotion's style type is csstype (no CSS custom-property keys)
        wrap=("{{background:spec.background??'#101710',['--onda-bg']:spec.background,['--onda-text']:spec.textColor,['--onda-accent']:spec.accent} as any}"
              if family=='onda' else "{{background:spec.background??'#101710'}}")
        component_cases.append(f"if(s.component==={json.dumps(scene['component'])}) return <AbsoluteFill style={wrap}><Piece{i} {{...({props})}}/></AbsoluteFill>;")
    clauses=["if(s.kind==='title') return <EditorialTitle title={s.title} subtitle={s.subtitle} eyebrow={s.eyebrow??spec.brand} background={spec.background} color={spec.textColor} accent={spec.accent} closing={s.closing??false} titleSize={s.titleSize} maxTitleSize={s.maxTitleSize} displayFont={spec.displayFont??spec.fontFamily??'Arial,sans-serif'} textFont={spec.textFont??spec.fontFamily??'Arial,sans-serif'} advance={spec.titleAdvance??0.54} anchor={s.anchor} rule={s.rule} {...s.props}/>;"]
    if 'character' in kinds:clauses.append("if(s.kind==='character') return <CharacterPresenter {...defaultCharacterProps} backgroundColor={spec.background??'#101710'} bodyColor={spec.accent??'#D7FF64'} accentColor={spec.accent??'#D7FF64'} textColor={spec.textColor??'#F3F1E9'} skinColor='#DFA06A' seed={spec.characterSeed??spec.brand??'video-forge'} {...s.props}/>;")
    if 'screen' in kinds:clauses.append("if(s.kind==='screen') return <ScreenFocus {...s} src={staticFile(s.src)}/>;")
    if 'three' in kinds:clauses.append("if(s.kind==='three') return <AbsoluteFill><ProceduralObject3D color={s.color??spec.accent}/>{s.title&&<div style={{position:'absolute',left:'6%',top:'9%',fontFamily:spec.displayFont??spec.fontFamily??'Arial',fontSize:56,color:spec.textColor??'#F3F1E9',fontWeight:750}}>{s.title}</div>}</AbsoluteFill>;")
    clauses.extend(component_cases)
    code='\n'.join(imports)+'''\nconst fps=spec.fps;
const frames=spec.scenes.map(s=>Math.max(1,Math.round(s.seconds*fps)));
const total=frames.reduce((a,b)=>a+b,0);
const Scene:React.FC<{s:any}>=({s})=>{'''+''.join(clauses)+'''return null;};
const Video:React.FC=()=>{let at=0;return <AbsoluteFill style={{background:spec.background??'#101710'}}>
{spec.scenes.map((s,i)=>{const start=at;at+=frames[i];return <Sequence key={i} from={start} durationInFrames={frames[i]}><DirectedBeat accent={spec.accent??'#D7FF64'} bg={spec.background??'#101710'} first={i===0} style={s.transition??spec.transition??'wipe'}><Scene s={s}/></DirectedBeat></Sequence>;})}
{production.narration&&<Audio src={staticFile('narration.wav')}/>}
{/* music bed is NOT mixed here; produce.py ducks it under the narration with ffmpeg sidechain and masters to EBU R128 */}
<MotionCaptions pages={production.pages} accent={spec.accent} fontSize={spec.width*.023}/>
{spec.brand&&<div style={{position:'absolute',right:'3%',top:'3%',fontFamily:'monospace',fontSize:spec.width*.01,color:spec.accent??'#D7FF64'}}>{spec.brand}</div>}
</AbsoluteFill>;};
registerRoot(()=><Composition id="Video" component={Video} durationInFrames={total} fps={fps} width={spec.width} height={spec.height}/>);
'''
    (out/'src/index.tsx').write_text(code)
    deps={'@remotion/cli':'4.0.538','remotion':'4.0.538','react':'19.2.3','react-dom':'19.2.3'}
    if any(x.startswith('onda/') for x in [scene.get('component','') for scene in data['scenes']]):deps['zod']='4.6.6'
    for dependency in component_deps:
        if dependency.startswith('@remotion/'):deps[dependency]='4.0.538'
        elif dependency not in {'react','react-dom','remotion','zod'}:raise ValueError(f'Selected component needs additional dependency {dependency}; inspect its upstream package manifest')
    if 'three' in kinds:deps.update({'@remotion/three':'4.0.538','@react-three/fiber':'9.6.0','three':'0.182.0','@types/three':'0.182.0'})
    if 'character' in kinds:deps.update({'@dicebear/core':'9.4.3','@dicebear/collection':'9.4.2'})
    package={'name':'video-forge-project','version':'1.0.0','private':True,'license':'MIT','dependencies':deps,'devDependencies':{'typescript':'5.9.3','@types/react':'19.2.7'},'scripts':{'studio':'remotion studio src/index.tsx','render':'remotion render src/index.tsx Video out/video.mp4','check':'tsc --noEmit'}}
    (out/'package.json').write_text(json.dumps(package,indent=2)+'\n')
    (out/'tsconfig.json').write_text(json.dumps({'compilerOptions':{'jsx':'react-jsx','target':'ES2020','lib':['ES2020','DOM'],'module':'ESNext','moduleResolution':'Bundler','esModuleInterop':True,'resolveJsonModule':True,'strict':True,'skipLibCheck':True,'noEmit':True},'include':['src']},indent=2)+'\n')
    if 'character' in kinds:shutil.copy2(ROOT/'library/vendor/rendercomp/LICENSE',out/'RENDERCOMP-LICENSE')
    print(json.dumps({'ok':True,'project':str(out.resolve()),'next':['copy scene media into public/','npm install --ignore-scripts','npm run check','npm run render']},indent=2))

if __name__=='__main__':main()
